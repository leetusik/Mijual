# key dates — the one countdown per rights type
# ---------------------------------------------------------------------------
@dataclass(frozen=True)
class KeyDate:
    """The date a rights type counts down to, with the Korean label the UI shows."""

    label: str
    value: date | None
    window: tuple[date | None, date | None] = (None, None)
    source: str = ""


def key_date(session, view: EventExposure) -> KeyDate:
    """The countdown date of one exposable event, per rights type.

    ① 증서 매매기간 종료일 (the moment the right stops being sellable), ② 전환청구
    개시일 (the moment the dilution can land), ③ 반대의사 통지 마감 (the first of
    the two-step deadline). A ``tbd`` field yields ``None`` — 추후결정 has no date.
    """
    if view.rights_type == "R1":
        field = view.fields.get("warrant_trading_period")
        value = field.value if field and field.exposable else None
        if isinstance(value, dict):
            return KeyDate(
                "신주인수권증서 매매 마감",
                _as_date(value.get("end_date")),
                (_as_date(value.get("start_date")), _as_date(value.get("end_date"))),
                "warrant_trading_period.end_date",
            )
        return KeyDate("신주인수권증서 매매 마감", None, source="warrant_trading_period (추후결정/미노출)")
    if view.rights_type == "R2":
        event = session.get(Event, view.event_id)
        facts = event_facts(session, event)
        return KeyDate(
            "전환청구 개시",
            facts.request_begin,
            (facts.request_begin, facts.request_end),
            "cvbdIsDecsn.cvrqpd_bgd",
        )
    field = view.fields.get("dissent_notice_procedure")
    value = field.value if field and field.exposable else None
    if isinstance(value, dict):
        return KeyDate(
            "반대의사 통지 마감",
            _as_date(value.get("notice_end_date")),
            (_as_date(value.get("notice_start_date")), _as_date(value.get("notice_end_date"))),
            "dissent_notice_procedure.notice_end_date",
        )
    return KeyDate("반대의사 통지 마감", None, source="dissent_notice_procedure (미노출)")


def _as_date(value: Any) -> date | None:
    if isinstance(value, date):
        return value
    if isinstance(value, str) and len(value) == 10:
        try:
            return date(int(value[:4]), int(value[5:7]), int(value[8:10]))
        except ValueError:
            return None
    return None


