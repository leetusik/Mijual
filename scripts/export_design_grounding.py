def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default=str(DEFAULT_OUT))
    parser.add_argument("--database-url", default=None)
    args = parser.parse_args(argv)

    out = Path(args.out)
    (out / "samples").mkdir(parents=True, exist_ok=True)
    today = today_kst()

    engine = make_engine(args.database_url)
    create_all(engine)
    ensure_columns(engine, Base)
    factory = make_session_factory(engine)

    written: list[str] = []
    gaps: list[str] = []
    with session_scope(factory) as session:
        pages: dict[str, Callable[[], str]] = {
            "board-snapshot.md": lambda: board_snapshot(session, today),
            "headline-numbers.md": lambda: headline_numbers(session, today),
            "copy-inventory.md": lambda: copy_inventory(session, today),
        }
        for name, build in pages.items():
            (out / name).write_text(build() + "\n", encoding="utf-8")
            written.append(name)

        for sample in SAMPLES:
            payload = sample_payload(session, sample, today)
            if payload is None:
                gaps.append(f"{sample.slug}: pinned rcept_no {sample.rcept_no} not in the corpus")
                continue
            path = out / "samples" / f"{sample.slug}.json"
            path.write_text(
                json.dumps(payload, ensure_ascii=False, indent=2, default=str) + "\n",
                encoding="utf-8",
            )
            written.append(f"samples/{sample.slug}.json")

    print(f"grounding pack : {out}")
    print(f"measured       : {today} (KST) — 0 OpenDART requests, 0 LLM calls")
    for name in written:
        print(f"  wrote        {name}")
    for gap in gaps:
        print(f"  GAP          {gap}")
    return 1 if gaps else 0


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())
