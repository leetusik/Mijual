def _cli(*args: str) -> str:
    """Run one of the package CLIs and capture its stdout verbatim. No network."""
    proc = subprocess.run(
        [sys.executable, "-m", *args], cwd=REPO, capture_output=True, text=True, check=True
    )
    return proc.stdout.rstrip()


def board_snapshot(session, today: date) -> str:
    views = [v for v in exposure_of_all(session) if v.exposable]
    rows = [(v, key_date(session, v)) for v in views]

    by_type: dict[str, int] = {}
    fields_by_type: dict[str, int] = {}
    for view, _ in rows:
        by_type[view.rights_type] = by_type.get(view.rights_type, 0) + 1
        fields_by_type[view.rights_type] = (
            fields_by_type.get(view.rights_type, 0) + len(view.renderable_fields)
        )

    out = [
        GENERATED_HEADER,
        "# Board snapshot",
        "",
        f"**Measured {today.isoformat()} (KST)** from the local Postgres corpus. "
        "0 OpenDART requests, 0 LLM calls.",
        "",
        "```",
        "# regenerate this whole file",
        ".venv/bin/python scripts/export_design_grounding.py",
        "# the same counts, straight from the CLI",
        ".venv/bin/python -m mijual.gates summary",
        "```",
        "",
        "## What the board holds today",
        "",
        "| | rights type | exposable events | renderable field instances |",
        "|---|---|---:|---:|",
    ]
    names = {"R1": "① 유상증자 신주인수권", "R2": "② 전환사채 오버행", "R3": "③ 주식매수청구권"}
    for code in ("R1", "R2", "R3"):
        out.append(
            f"| {code} | {names[code]} | {by_type.get(code, 0)} | {fields_by_type.get(code, 0)} |"
        )
    out.append(
        f"| | **합계** | **{sum(by_type.values())}** | **{sum(fields_by_type.values())}** |"
    )
    out += [
        "",
        "A *renderable field instance* is a gate-passing field on an exposable event — what P3 may "
        "actually put on a card. ② carries far fewer of them per event on purpose: its countdown is "
        "`API` tier (전환가액 · 전환청구기간 · 오버행), and the 본문 fields are additive colour.",
        "",
        "## The countdown each type counts down to",
        "",
        "| | 카운트다운 | source field |",
        "|---|---|---|",
        "| ① | 신주인수권증서 매매 마감 | `warrant_trading_period.end_date` |",
        "| ② | 전환청구 개시 | `cvbdIsDecsn.cvrqpd_bgd` |",
        "| ③ | 반대의사 통지 마감 | `dissent_notice_procedure.notice_end_date` |",
        "",
        "## Urgency distribution",
        "",
        "Counted against two anchors: **today** and the fixed judging anchor "
        f"**{JUDGING_ANCHOR.isoformat()}**. `≤7d` / `≤30d` are inclusive windows starting at the "
        "anchor and **`≤7d` is a subset of `≤30d`**; `30일 초과` is a key date further out; `지남` is "
        "a key date already behind the anchor; `날짜 없음` is an exposable event whose countdown date "
        "is 추후결정 or not rendered. `≤30d + 30일 초과 + 지남 + 날짜 없음 = 계`.",
        "",
    ]
    for anchor, caption in ((today, f"anchor = today ({today.isoformat()})"),
                            (JUDGING_ANCHOR, f"anchor = {JUDGING_ANCHOR.isoformat()} (심사 기준일)")):
        out += [
            f"**{caption}**",
            "",
            "| | ≤7d | ≤30d | 30일 초과 | 지남 | 날짜 없음 | 계 |",
            "|---|---:|---:|---:|---:|---:|---:|",
        ]
        groups = [(code, [kd for v, kd in rows if v.rights_type == code])
                  for code in ("R1", "R2", "R3")]
        for code, group in groups + [("**계**", [kd for _, kd in rows])]:
            beyond = (
                len(group)
                - _within(group, anchor, 30)
                - _past(group, anchor)
                - sum(1 for k in group if k.value is None)
            )
            out.append(
                f"| {code} | {_within(group, anchor, 7)} | {_within(group, anchor, 30)} | "
                f"{beyond} | {_past(group, anchor)} | "
                f"{sum(1 for k in group if k.value is None)} | {len(group)} |"
            )
        out.append("")
    out += [
        "**`지남` does not mean the same thing in every type.** For ① it is a right that has already "
        "lapsed (the 매매기간 closed) and for ③ a deadline that has passed — both are history. For ② a "
        "past 전환청구 개시일 means the window is **already open**: the dilution is live right now, not "
        "over. Whether and how the board shows each of those is a design question (R2), not a data one.",
        "",
    ]

    out += ["## Most urgent live events, per type", "",
            "The top of each type's board today — the rows a designer should lay out first.", ""]
    for code in ("R1", "R2", "R3"):
        live = sorted(
            ((v, k) for v, k in rows if v.rights_type == code and k.value and k.value >= today),
            key=lambda pair: pair[1].value,
        )[:5]
        out += [f"### {code} {names[code]}", "",
                "| 회사 | 카운트다운 | 기준일 | D-day | rcept_no |", "|---|---|---|---|---|"]
        if not live:
            out.append("| _(오늘 기준 남은 일정 없음)_ | | | | |")
        for view, kd in live:
            dd = d_day(kd.value, today)
            out.append(
                f"| {view.corp_name or view.corp_code} | {kd.label} | {kd.value} | "
                f"`{dd.label}` | `{view.rcept_no}` |"
            )
        out.append("")

    out += [
        "## The same counts from the CLI (verbatim)",
        "",
        "```",
        _cli("mijual.gates", "summary"),
        "```",
        "",
        "The `blocked` line is the price of the trust gate — events and fields that exist, are "
        "recorded with a reason code, and are **not** on the board. The admin panel (R7) is the only "
        "surface that shows them.",
        "",
    ]
    return "\n".join(out)


def _within(keys: list[KeyDate], anchor: date, days: int) -> int:
    return sum(1 for k in keys if k.value is not None and 0 <= (k.value - anchor).days <= days)


def _past(keys: list[KeyDate], anchor: date) -> int:
    return sum(1 for k in keys if k.value is not None and (k.value - anchor).days < 0)


