#!/usr/bin/env python3
"""Export the P3 design grounding pack — real product content for the design rounds.

`design-cowork` forbids lorem: every design round must sit on real Korean copy,
real numbers and real edge states. Claude Design reads this repository through its
repo connection but cannot query Postgres, so this tool exports a **dated,
regenerable snapshot** of the live corpus into `docs/reference/design/grounding/`.

    .venv/bin/python scripts/export_design_grounding.py

**0 OpenDART requests, 0 LLM calls.** Everything is read from the local Postgres
corpus through the same modules the product will use (`mijual.gates.exposure`,
`mijual.cb`, `mijual.estimate`, `mijual.calc`), so a figure here is the figure the
product would render — not a hand-copied one.

This is a **documentation tool, not product code**. It writes only under the output
directory, and nothing under `src/mijual/` depends on it.

What it writes (everything else in the pack is hand-written prose):

* `board-snapshot.md`   — exposable-event counts by rights type, renderable field
  instances, urgency distribution against two anchors, most urgent live events
* `headline-numbers.md` — the 소멸가치 report verbatim (table + 발표용 문장)
* `copy-inventory.md`   — every reason code, notice and field label in Korean
* `samples/*.json`      — the pinned per-type edge-state samples

Sample selection is **pinned by `rcept_no`** in :data:`SAMPLES` so the pack stays
stable across regenerations: a sample that disappears is reported as a gap rather
than silently swapped for another event.
"""

