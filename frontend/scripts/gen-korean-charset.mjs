#!/usr/bin/env node
// Generate scripts/korean-charset.txt from the Korean text the app actually renders, so the
// Noto Sans KR subset (scripts/subset_noto_sans_kr.sh) can never go stale and drop a syllable.
//
// WHY THIS EXISTS. Adopted from ~/projects/personal/changple_web at the operator's instruction
// ("research changple_web's case for the korean font, use same with it"), including the reason
// their comment records: their charset was hand-maintained, fell behind the UI copy, and the
// missing precomposed Hangul made the browser decompose those NFC syllables into conjoining jamo
// and render them split apart (자모 분리 / "decomposed Korean"). Auto-extracting every rendered
// syllable removes the whole failure class, and a hand-edited list is how it comes back.
//
// WHAT MIJUAL DOES DIFFERENTLY, AND WHY. changple_web subsets to rendered glyphs only and lets
// dynamic database copy fall back to the OS face. Mijual cannot: it renders **DART company names**
// on the board, on every event page and throughout /ask, and those are dynamic — a rendered-glyph
// subset would put half of what the reader actually looks at in a different typeface from the UI
// around it. So this file is only the *floor*; subset_noto_sans_kr.sh adds the full 11,172-syllable
// Hangul block on top of it. See that script's header for the measured payloads behind that choice.
// The output still matters: it is what proves the app's own copy is covered even if the syllable
// policy is ever narrowed again, and it carries the non-Hangul Korean punctuation the ranges miss.
//
// Scope: rendered frontend source (app/, components/, lib/) in .ts/.tsx/.json/.md, excluding tests.
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const DIRS = ["app", "components", "lib"];
const OUT = join(ROOT, "scripts/korean-charset.txt");
const EXTS = new Set([".ts", ".tsx", ".json", ".md"]);
const isTest = (p) => /(^|\/)(test|__tests__)\//.test(p) || /\.test\.[tj]sx?$/.test(p);

// Hangul syllables (U+AC00–D7A3) + Hangul Compatibility Jamo (U+3130–318F, e.g. ㅋㅋ and the
// standalone 자음/모음 the ops surface uses). Deliberately NOT the conjoining-jamo block
// U+1100–11FF — including those is what enables the decomposition bug.
const KOREAN = /[가-힣㄰-㆏]/gu;

function walk(dir) {
  const out = [];
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, e.name);
    if (e.isDirectory()) out.push(...walk(full));
    else if (e.isFile() && EXTS.has(full.slice(full.lastIndexOf(".")))) out.push(full);
  }
  return out;
}

const chars = new Set();
let scanned = 0;
for (const dir of DIRS) {
  const abs = join(ROOT, dir);
  if (!existsSync(abs)) continue;
  for (const file of walk(abs)) {
    const rel = relative(ROOT, file);
    if (isTest(rel)) continue;
    scanned += 1;
    for (const m of readFileSync(file, "utf8").matchAll(KOREAN)) chars.add(m[0]);
  }
}

const sorted = [...chars].sort();
const header =
  "# AUTO-GENERATED by scripts/gen-korean-charset.mjs — do not edit by hand.\n" +
  "# Every Korean glyph the frontend renders (app/, components/, lib/; excl. tests).\n" +
  "# Regenerated by subset_noto_sans_kr.sh, which also adds the full Hangul block on top.\n";
writeFileSync(OUT, header + sorted.join("") + "\n", "utf8");
console.log(
  `korean-charset: ${sorted.length} unique Korean chars from ${scanned} files -> ${relative(ROOT, OUT)}`,
);
